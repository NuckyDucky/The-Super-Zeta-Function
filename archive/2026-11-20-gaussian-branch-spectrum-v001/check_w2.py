"""Two branch-sensitive spectral readings at w=2. Python 3.10+, python-flint 0.9.0.
Run: python -B check_w2.py
The JSON written to stdout includes both finite arithmetic and analytic tails.
"""
import json
from math import isqrt, prod

from flint import acb, arb, ctx

DELTA = (-5045155, 1027708)
CONDUCTOR = ((41, 32), (457, 109), (1414835497, 516876951))
LATTICE_CUTOFF = 65536
EULER_CUTOFF = 16384


def quadratic_symbol(x, p):
    residue = pow(x % p, (p - 1) // 2, p)
    if residue == p - 1:
        return -1
    if residue in (0, 1):
        return residue
    raise ArithmeticError("Unexpected Euler criterion result")


def conductor_sign(m, n, side):
    return prod(quadratic_symbol(m + side * n * t, p) for p, t in CONDUCTOR)


def direct_prime_sign(p, a, b, side):
    # Reduce the original Gaussian discriminant at the ideal generated by a+bi.
    i_image = -a * pow(b, -1, p) % p
    assert (i_image**2 + 1) % p == 0
    return quadratic_symbol(DELTA[0] + side * DELTA[1] * i_image, p)


def report(partial, error):
    return {
        "partial": str(partial),
        "absolute_tail_upper": str(error.upper()),
        "total_lower": str((partial - error).lower()),
        "total_upper": str((partial + error).upper()),
    }


def angular_lattice(sides):
    sums = {side: arb(0) for side in sides}
    count = 0
    for m in range(1, isqrt(LATTICE_CUTOFF) + 1):
        for n in range(isqrt(LATTICE_CUTOFF - m*m) + 1):
            norm = m*m + n*n
            # The imaginary part of (m+ni)^4 / norm^4 is the w=2 summand.
            im = arb(4*m*n*(m*m - n*n)) / norm**4
            for side in sides:
                sums[side] += conductor_sign(m, n, side) * im
            count += 1
    # The ideal count at norm j is bounded by d(j). D(t)<=t(1+log t)
    # and Abel summation bound sum_{j>X} d(j)/j^2 by 2(log X+2)/X.
    tail = 2*(arb(LATTICE_CUTOFF).log() + 2)/LATTICE_CUTOFF
    return sums, tail, count


def zero_moment(sides):
    sums = {side: arb(0) for side in sides}
    for p in range(5, EULER_CUTOFF + 1, 4):
        if any(p % d == 0 for d in range(2, isqrt(p) + 1)):
            continue
        for a in range(1, isqrt(p) + 1):
            b = isqrt(p - a*a)
            if a*a + b*b == p:
                break
        else:
            raise ArithmeticError("Missing generator at split prime")
        signs = {side: tuple(direct_prime_sign(p, a, j, side) for j in (b, -b))
                 for side in sides}
        omega = acb(a, b)**4 / p**2
        k, pk, phase = 1, p, omega
        log_squared = arb(p).log()**2
        while pk <= EULER_CUTOFF:
            for side, (first, second) in signs.items():
                sums[side] += k*(first**k - second**k)*phase.imag*log_squared / pk**2
            k += 1
            pk *= p
            phase *= omega
    # Inert primes and the prime above 2 have real phase. At each norm j,
    # at most two prime powers contribute; k(log p)^2 <= (log j)^2.
    # Integrate 2 (log t)^2/t^2 from X to infinity to cover the omitted terms.
    log_x = arb(EULER_CUTOFF).log()
    tail = 2*(log_x**2 + 2*log_x + 2)/EULER_CUTOFF
    return sums, tail


def main():
    if not __debug__:
        raise RuntimeError("Enable Python assertions to run this verification.")
    ctx.prec = 160
    sides = (1, -1)
    lattice, lattice_tail, count = angular_lattice(sides)
    moment, moment_tail = zero_moment(sides)
    for readings, tail in ((lattice, lattice_tail), (moment, moment_tail)):
        assert readings[1].overlaps(-readings[-1])
        assert readings[1] > tail and readings[-1] < -tail
    for readings, tail, low, high in (
        (lattice, lattice_tail, arb("0.0052611"), arb("0.0060602")),
        (moment, moment_tail, arb("0.0595888"), arb("0.0878060")),
    ):
        for side in sides:
            oriented = side * readings[side]
            assert low < oriented - tail and oriented + tail < high
    result = {
        "w": 2,
        "precision_bits": ctx.prec,
        "twist": "(z/abs(z))^4, same Gaussian orientation for both branches",
        "lattice_norm_cutoff": LATTICE_CUTOFF,
        "nonzero_ideals_used_in_lattice_sum": count,
        "euler_prime_power_norm_cutoff": EULER_CUTOFF,
        "zero_moment_identity": "Im (log W)''(2) = -Im sum_rho (2-rho)^(-2), via Hadamard",
        "zero_coordinates_evaluated": 0,
        "by_branch": {},
    }
    for side, name in zip(sides, ("A+2iN", "A-2iN")):
        result["by_branch"][name] = {
            "imaginary_part_of_W": report(lattice[side], lattice_tail),
            "zero_moment_from_euler_side": report(moment[side], moment_tail),
        }
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
