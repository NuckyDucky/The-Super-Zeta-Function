"""Generate checkable endpoint witnesses for the outer Gaussian cells."""

import argparse
from fractions import Fraction
from math import ceil, factorial, floor
from pathlib import Path
import re

PACKET = Path(__file__).resolve().parents[1] / "source"


def exp_bounds(value):
    whole = floor(value)
    part = value - whole
    series = sum(part**k / factorial(k) for k in range(10))
    return (
        Fraction("2.718281828")**whole * series,
        Fraction("2.718281829")**whole * (series + Fraction(11, 36288000)),
    )


def real(value):
    return f"({value.numerator} : ℝ) / {value.denominator}"


def exp_proof(value, side):
    whole = floor(value)
    part = real(value - whole)
    return f"(exp_bounds {whole} (y := {part}) (by norm_num) (by norm_num)).{side}"


def cell(j, low, high):
    left, right = Fraction(j, 64), Fraction(j + 1, 64)
    resolution = 100_000
    ulo = Fraction(floor(resolution * exp_bounds(left)[0] / 1638903), resolution)
    uhi = Fraction(ceil(resolution * exp_bounds(right)[1] / 1638902), resolution)
    q = Fraction(ceil(10**8 / exp_bounds(ulo)[0]), 10**8)
    e = Fraction(ceil(10**7 * (1 / (1 - q)**2 - 1)), 10**7)
    dlo, dhi = ulo - left / 2, uhi - right / 2
    L, U = Fraction(low, 1_000_000), Fraction(high, 1_000_000)
    if (L * exp_bounds(dhi)[1] > 1 - e or U * exp_bounds(dlo)[0] < 1 + e):
        raise ValueError(f"First-term bounds do not fit the stored row {j}.")

    def lower_step(value):
        return f"""    have h := {exp_proof(value, 1)}
    norm_num [expLo, expPoly, Finset.sum_range_succ, Nat.factorial] at h
    linarith only [h]"""

    def upper_step(value):
        return f"""    have h := {exp_proof(value, 2)}
    norm_num [expHi, expPoly, Finset.sum_range_succ, Nat.factorial] at h
    linarith only [h]"""

    lower = f"  ·\n{upper_step(dhi)}\n" if low else ""
    return f"""private theorem cell_{j}_scalar :
    ∀ x ∈ Icc ({real(left)}) ({real(right)}),
      {real(L)} ≤ QuarticKernel.kernel x ∧ QuarticKernel.kernel x ≤ {real(U)} := by
  apply check_pointwise_cell (uLo := {real(ulo)}) (uHi := {real(uhi)})
    (q := {real(q)}) (e := {real(e)}) <;> try norm_num
  ·
{lower_step(left)}
  ·
{upper_step(right)}
  ·
{lower_step(ulo)}
{lower}  ·
{lower_step(dlo)}

theorem cell_{j} (x : ℝ) (hx : x ∈ Icc (node {j} : ℝ) (node {j+1} : ℝ)) :
    (lowerK {j} : ℝ) ≤ QuarticKernel.kernel x ∧
      QuarticKernel.kernel x ≤ (upperK {j} : ℝ) := by
  have hdata : data[{j}]?.getD (0,0) = ({low},{high}) := by decide
  rw [lowerK, upperK, hdata]
  have h := cell_{j}_scalar x (by norm_num [node] at hx ⊢; exact hx)
  norm_num at h ⊢
  exact h
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--first", type=int, default=1051)
    parser.add_argument("--end", type=int, default=1116)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if not 0 <= args.first < args.end <= 1152:
        raise ValueError("The range must be a nonempty interval of grid rows.")
    data = (PACKET / "QuarticGridData.lean").read_text(encoding="utf-8")
    rows = [tuple(map(int, row)) for row in re.findall(r"\((\d+), (\d+)\)", data)]
    output = [
        "/- Endpoint witnesses generated by generate_pointwise.py. -/",
        "import QuarticPointwise",
        "",
        "open Set",
        "namespace QuarticGrid",
        "set_option maxRecDepth 20000",
        "",
    ]
    for j in range(args.first, args.end):
        output.append(cell(j, *rows[j]))
    output += ["end QuarticGrid", ""]
    args.output.write_text("\n".join(output), encoding="utf-8")


if __name__ == "__main__":
    main()
