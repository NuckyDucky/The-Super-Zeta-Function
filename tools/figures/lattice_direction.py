"""Rebuild the figures for the Eisenstein weights and marked Gaussian directions.

Run with Python 3 and Pillow. Source: docs/proofs/marked-gaussian-direction.md
and archive/2026-11-20-dedekind-phase-v001/README.md.
"""

from functools import lru_cache
from math import atan2, cos, pi, sin, sqrt
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


OUT = Path(__file__).resolve().parents[2] / "docs" / "figures"
SIZE = (1120, 590)
PAPER = "#FAF8F2"
INK = "#18323F"
MUTED = "#4F6470"
GRID = "#D4DAD6"
TEAL = "#006D70"
OCHRE = "#9D521C"
PALE_TEAL = "#D4E8E3"
PALE_OCHRE = "#F5E1CE"
CONDUCTOR = (41, 457, 1414835497)
DELTA = (-5045155, 1027708)


@lru_cache
def font(size, bold=False):
    names = (["DejaVuSans-Bold.ttf", "segoeuib.ttf"] if bold
             else ["DejaVuSans.ttf", "segoeui.ttf"])
    for name in names:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            continue
    raise OSError("Install DejaVu Sans or Segoe UI to generate the figures.")


def txt(draw, xy, words, size=22, fill=INK, *, bold=False, anchor="la"):
    draw.text(xy, words, font=font(size, bold), fill=fill, anchor=anchor)


def page(title, subtitle):
    im = Image.new("RGB", SIZE, PAPER)
    d = ImageDraw.Draw(im)
    txt(d, (36, 17), title, 35, bold=True)
    txt(d, (38, 68), subtitle, 22, MUTED)
    d.line((37, 110, 1083, 110), fill=GRID, width=2)
    return im, d


def dot(d, center, radius, fill, outline=None, width=1):
    x, y = center
    d.ellipse((x-radius, y-radius, x+radius, y+radius), fill, outline, width)


def arrow(d, start, end, fill, width=4):
    d.line([start, end], fill=fill, width=width)
    x, y = end
    angle = atan2(y-start[1], x-start[0])
    d.polygon([(x, y), (x-14*cos(angle-.43), y-14*sin(angle-.43)),
               (x-14*cos(angle+.43), y-14*sin(angle+.43))], fill)


def paths(frames, durations, filename):
    # An independent adaptive palette for each frame preserves the type and colors.
    images = [im.convert("P", palette=Image.Palette.ADAPTIVE, colors=96) for im in frames]
    images[0].save(OUT / filename, save_all=True, append_images=images[1:],
                   duration=durations, loop=0, optimize=True, disposal=1)


def draw_lattice(u):
    im, d = page("The lattice of the two ordered exponents",
                 "The angle u selects the basis 1, τ. The marked point always has coefficients (1, 1).")
    # ratio U/V = -exp(-2iu), with positive imaginary part.
    tau = complex(-cos(2*u), sin(2*u))
    cx, cy, scale = 280, 364, 86
    def loc(z):
        return (cx+scale*z.real, cy-scale*z.imag)
    d.line((54, cy, 499, cy), fill=GRID, width=2)
    d.line((cx, 151, cx, 530), fill=GRID, width=2)
    for m in range(-5, 6):
        for n in range(-4, 5):
            p = loc(m+n*tau)
            if 57 <= p[0] <= 499 and 149 <= p[1] <= 528:
                dot(d, p, 3, MUTED)
    cell = [loc(z) for z in (0j, 1, 1+tau, tau)]
    d.polygon(cell, fill=PALE_TEAL)
    d.line([*cell, cell[0]], fill=TEAL, width=2)
    for z, label, off in [(1,"1",(7,1)),(tau,"τ",(-19,-27))]:
        p=loc(z)
        arrow(d, loc(0j), p, TEAL)
        txt(d,(p[0]+off[0],p[1]+off[1]),label,26,TEAL,bold=True)
    dot(d, loc(1+tau), 7, OCHRE)
    ex, ey = loc(1+tau)
    txt(d,(ex+8,ey-30),"1 + τ",24,OCHRE,bold=True)
    txt(d,(cx-12,cy+4),"0",18,MUTED,anchor="ra")
    txt(d,(504,cy+4),"Re",17,MUTED,anchor="ra")
    txt(d,(cx+7,141),"Im",17,MUTED)
    d.line((538,140,538,533),fill=GRID,width=2)
    txt(d,(572,153),"Ordered ratio",22,MUTED)
    txt(d,(572,188),"τ = −exp(−2iu)",35,bold=True)
    txt(d,(572,258),f"u = {u:.3f} rad",30,TEAL,bold=True)
    txt(d,(572,311),"Squared length of the marked point",22,MUTED)
    txt(d,(572,346),f"|1 + τ|² = {abs(1+tau)**2:.3f}",33,OCHRE,bold=True)
    txt(d,(572,428),"u = π/6     Eisenstein lattice",24)
    txt(d,(572,468),"u = π/4     square lattice",24)
    txt(d,(38,550),"Both axes use the same unit length. The highlighted cell is generated by 1 and τ.",20,MUTED)
    return im


def prime_weights():
    im, d = page("Which prime powers enter the field’s prime sum?",
                 "Each entry is the coefficient of log p at n = pʲ for the Eisenstein field.")
    cols = (524, 668, 812, 956)
    for x,j in zip(cols, range(1,5)):
        txt(d,(x,146),f"j = {j}",25,MUTED,bold=True,anchor="ma")
    for row, (p, kind) in enumerate([(2,"inert"),(3,"ramified"),(7,"split")]):
        y=206+row*82
        chi={2:-1,0:0,1:1}[p%3]
        txt(d,(48,y+4),f"p = {p}",29,bold=True)
        txt(d,(165,y+9),kind,25,MUTED)
        for x,j in zip(cols,range(1,5)):
            w=1+chi**j
            fill,ink = [(PAPER,MUTED),(PALE_OCHRE,OCHRE),(PALE_TEAL,TEAL)][w]
            d.rounded_rectangle((x-57,y-3,x+57,y+56),radius=9,outline=GRID,fill=fill,width=2)
            txt(d,(x,y+26),str(w),32,ink,bold=True,anchor="mm")
    d.line((38,459,1080,459),fill=GRID,width=2)
    txt(d,(48,477),"At 2, 4 and 8 the coefficients are 0, 2 and 0.",26,bold=True)
    txt(d,(48,523),"The prime above 2 first contributes at norm 4. In general the coefficient is 1 + χ₋₃(p)ʲ.",20,MUTED)
    im.save(OUT/"lattice-prime-weights.png",optimize=True)


def symbol(value,p):
    r=pow(value%p,(p-1)//2,p)
    return -1 if r==p-1 else r


def gaussian_sign(x,y):
    p=x*x+y*y
    t=(-x*pow(y,-1,p))%p
    return symbol(DELTA[0]+DELTA[1]*t,p)


def prime_directions():
    # Associates place both conjugate ideals in the same first quadrant.
    pairs=[((3,2),(2,3)),((6,1),(1,6)),((8,3),(3,8))]
    assert [[gaussian_sign(*v) for v in pair] for pair in pairs]==[[-1,-1],[1,1],[1,-1]]
    frames=[]
    for pair in pairs:
        p=sum(t*t for t in pair[0])
        im,d=page("Two Gaussian directions at one prime norm",
                  "Unit rotations place one generator of each conjugate ideal in the first quadrant.")
        cx,cy,scale=100,490,36
        def pos(x,y): return cx+scale*x,cy-scale*y
        for j in range(10):
            d.line((pos(j,0),pos(j,9)),fill=GRID,width=1)
            d.line((pos(0,j),pos(9,j)),fill=GRID,width=1)
        d.line((pos(0,0),pos(9,0)),fill=MUTED,width=2)
        d.line((pos(0,0),pos(0,9)),fill=MUTED,width=2)
        for j in (0,3,6,9):
            txt(d,(pos(j,0)[0],cy+4),str(j),17,MUTED,anchor="ma")
            if j: txt(d,(cx-8,pos(0,j)[1]),str(j),17,MUTED,anchor="rm")
        txt(d,(447,478),"Re",20,MUTED)
        txt(d,(78,130),"Im",20,MUTED)
        ring=[pos(sqrt(p)*cos(k*pi/160),sqrt(p)*sin(k*pi/160)) for k in range(81)]
        d.line(ring,fill=MUTED,width=2)
        for (x,y),color in zip(pair,(TEAL,OCHRE)):
            point=pos(x,y)
            arrow(d,pos(0,0),point,color)
            dot(d,point,8,color)
            txt(d,(point[0]+9,point[1]-29),f"({x}, {y})",21,color,bold=True)
        d.line((497,140,497,518),fill=GRID,width=2)
        txt(d,(527,145),f"Prime norm {p}",31,bold=True)
        txt(d,(529,201),"Generator",21,MUTED)
        txt(d,(728,201),"Angle (rad)",21,MUTED)
        txt(d,(942,201),"Sign",21,MUTED)
        for i,((x,y),color) in enumerate(zip(pair,(TEAL,OCHRE))):
            yy=250+i*64
            txt(d,(527,yy),f"{x} + {y}i",30,color,bold=True)
            txt(d,(731,yy+4),f"{atan2(y,x):.4f}",26)
            txt(d,(946,yy),"+1" if gaussian_sign(x,y)==1 else "−1",30,bold=True)
        txt(d,(527,396),"The sign tests whether the quartic",22)
        txt(d,(527,429),"discriminant is a square modulo",22)
        txt(d,(527,462),"the marked Gaussian prime.",22)
        txt(d,(38,550),"Each frame compares one rational prime. The arc has squared radius equal to that prime.",20,MUTED)
        frames.append(im)
    frames[-1].save(OUT/"direction-marked-primes.png",optimize=True)
    paths(frames,[2700,2700,4200],"direction-marked-primes.gif")


def same_ray():
    im,d=page("One ray can carry both quartic signs",
              "The primitive generator condition matters when a direction is used to recover an ideal.")
    origin=78
    fac=12.5
    y=189
    arrow(d,(origin,y),(1047,y),MUTED,width=3)
    for x in (0,20,40,60):
        xx=origin+fac*x
        d.line((xx,y-5,xx,y+5),fill=MUTED,width=2)
        txt(d,(xx,y+9),str(x),17,MUTED,anchor="ma")
    for x,color in [(1,TEAL),(73,OCHRE)]:
        xx=origin+x*fac
        dot(d,(xx,y),7,color)
        txt(d,(xx,y-43),str(x),25,color,bold=True,anchor="ma")
    txt(d,(665,y+35),"Real Gaussian coordinate",19,MUTED,anchor="ma")
    d.line((38,259,1080,259),fill=GRID,width=2)
    headings=[(50,"Ideal"),(260,"Direction"),(537,"Three residue signs"),(920,"Product")]
    for xx,h in headings: txt(d,(xx,287),h,22,MUTED,bold=True)
    for k,(z,color) in enumerate([(1,TEAL),(73,OCHRE)]):
        yy=345+66*k
        vals=[symbol(z,p) for p in CONDUCTOR]
        signed=lambda v:"+1" if v==1 else "−1"
        txt(d,(50,yy),f"({z})",29,color,bold=True)
        txt(d,(260,yy),"0 radians",27)
        txt(d,(537,yy),"    ".join(map(signed,vals)),27)
        txt(d,(929,yy),signed(vals[0]*vals[1]*vals[2]),30,color,bold=True)
    txt(d,(43,522),"Scaling 1 to 73 preserves its angle. The character changes sign on the product ideal (73).",21,MUTED)
    im.save(OUT/"direction-same-ray.png",optimize=True)


